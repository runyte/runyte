//! Imported palettes that share one role mapping.
//!
//! Backgrounds, text, and [`Palette::syntax`] come from the upstream revision
//! recorded in `THIRD_PARTY_NOTICES.md`. Some roles are Runyte's own: carets
//! and notification colours below 3:1 and one-key jump labels below 4.5:1 step
//! toward legibility, and a selection ground that an upstream leaves too close
//! to its background, or that its text cannot be read on, becomes a
//! palette-local tint. `selection_primary`, any `jump_text_muted` override, and
//! status grounds for themes without a status colour are Runyte's as well.

use super::{
    CHANGE_ADDED_DARK, CHANGE_ADDED_LIGHT, CHANGE_MODIFIED_DARK, CHANGE_MODIFIED_LIGHT,
    CHANGE_REMOVED_DARK, CHANGE_REMOVED_LIGHT, DIFF_ADDED_DARK, DIFF_ADDED_LIGHT,
    DIFF_CHANGED_DARK, DIFF_CHANGED_LIGHT, DIFF_REMOVED_DARK, DIFF_REMOVED_LIGHT,
    JUMP_LABEL_DARK_PRIMARY, JUMP_LABEL_DARK_SECONDARY, JUMP_LABEL_LIGHT_PRIMARY,
    JUMP_LABEL_LIGHT_SECONDARY, ThemeDefinition, syntax_theme,
};

/// The code scopes, in the order [`Palette::syntax`] lists their colours.
const SCOPES: [&str; 16] = [
    "attribute",
    "comment",
    "constant",
    "constructor",
    "function",
    "keyword",
    "label",
    "namespace",
    "number",
    "operator",
    "property",
    "punctuation",
    "string",
    "tag",
    "type",
    "variable",
];

/// One upstream theme, already mapped onto Runyte's roles.
pub(super) struct Palette {
    pub(super) name: &'static str,
    pub(super) light: bool,
    pub(super) background: &'static str,
    pub(super) foreground: &'static str,
    pub(super) muted: &'static str,
    pub(super) jump_text_muted: Option<&'static str>,
    pub(super) accent: &'static str,
    pub(super) cursor_normal: Option<&'static str>,
    pub(super) cursor_insert: &'static str,
    pub(super) cursor_select: &'static str,
    pub(super) cursor_command: &'static str,
    pub(super) directory: &'static str,
    pub(super) selection: &'static str,
    pub(super) selection_primary: &'static str,
    pub(super) status_background: &'static str,
    pub(super) status_foreground: &'static str,
    pub(super) error: &'static str,
    pub(super) warning: &'static str,
    pub(super) info: &'static str,
    pub(super) jump_label_immediate: &'static str,
    /// Added, removed and changed row grounds, for the few palettes whose own
    /// text cannot be read on the shared ones.
    pub(super) diff_rows: Option<[&'static str; 3]>,
    pub(super) syntax: [&'static str; 16],
}

impl Palette {
    pub(super) fn entry(&self) -> (String, ThemeDefinition) {
        (self.name.to_owned(), self.theme())
    }

    fn theme(&self) -> ThemeDefinition {
        let shared = if self.light {
            [
                JUMP_LABEL_LIGHT_PRIMARY,
                JUMP_LABEL_LIGHT_SECONDARY,
                CHANGE_ADDED_LIGHT,
                CHANGE_MODIFIED_LIGHT,
                CHANGE_REMOVED_LIGHT,
                DIFF_ADDED_LIGHT,
                DIFF_REMOVED_LIGHT,
                DIFF_CHANGED_LIGHT,
            ]
        } else {
            [
                JUMP_LABEL_DARK_PRIMARY,
                JUMP_LABEL_DARK_SECONDARY,
                CHANGE_ADDED_DARK,
                CHANGE_MODIFIED_DARK,
                CHANGE_REMOVED_DARK,
                DIFF_ADDED_DARK,
                DIFF_REMOVED_DARK,
                DIFF_CHANGED_DARK,
            ]
        };
        let [
            jump_primary,
            jump_secondary,
            added,
            modified,
            removed,
            diff_added,
            diff_removed,
            diff_changed,
        ] = shared;
        let [diff_added, diff_removed, diff_changed] =
            self.diff_rows
                .unwrap_or([diff_added, diff_removed, diff_changed]);
        let scopes: Vec<_> = SCOPES.into_iter().zip(self.syntax).collect();
        ThemeDefinition {
            background: self.background.into(),
            foreground: self.foreground.into(),
            muted: self.muted.into(),
            whitespace: None,
            jump_text_muted: self.jump_text_muted.map(Into::into),
            accent: self.accent.into(),
            command: None,
            cursor_normal: self.cursor_normal.map(Into::into),
            cursor_insert: Some(self.cursor_insert.into()),
            cursor_replace: None,
            cursor_select: Some(self.cursor_select.into()),
            cursor_command: Some(self.cursor_command.into()),
            cursor_secondary: None,
            directory: Some(self.directory.into()),
            destination_file: None,
            destination_explorer: None,
            destination_generated: None,
            destination_scratch: None,
            destination_terminal: None,
            selection: self.selection.into(),
            selection_primary: Some(self.selection_primary.into()),
            fuzzy_match_secondary: None,
            fuzzy_match_primary: None,
            status_background: self.status_background.into(),
            status_foreground: self.status_foreground.into(),
            error: self.error.into(),
            warning: Some(self.warning.into()),
            info: Some(self.info.into()),
            jump_label_immediate: Some(self.jump_label_immediate.into()),
            jump_label_primary: jump_primary.into(),
            jump_label_secondary: jump_secondary.into(),
            change_added: Some(added.into()),
            change_modified: Some(modified.into()),
            change_removed: Some(removed.into()),
            diff_added: Some(diff_added.into()),
            diff_removed: Some(diff_removed.into()),
            diff_changed: Some(diff_changed.into()),
            terminal: std::collections::HashMap::new(),
            syntax: syntax_theme(&scopes),
        }
    }
}

